(* # Restricted isometry of matrices with independent subexponential columns  *)
(*                                                                            *)
(* Plan (phase 5, stage 3, item S3 of lane C, one of the four hard items of   *)
(* AGENTS.md; names come with the proofs).                                    *)
(*                                                                            *)
(* The estimate of Adamczak, Litvak, Pajor and Tomczak-Jaegermann (Constr.    *)
(* Approx. 2011, Theorem 3.2), cited by Koehler and Sohn (arXiv 2608.27372,   *)
(* lines 2192-2221): for independent columns w_1, ..., w_n of R^D whose       *)
(* linear forms <w_i, u>, |u| = 1, are subexponential with constant psi, and  *)
(* 1 <= m <= min (n, D),                                                      *)
(*   delta_m = sup_{|I| <= m} |W_I^T W_I / D - I|_op                          *)
(* satisfies, with L = log (e n / (m sqrt (m / D))),                          *)
(*   P(delta_m >= C sqrt (m / D) L + theta)                                   *)
(*     <= exp (- c sqrt m L) + P(max_i | |w_i|^2 / D - 1 | >= theta),         *)
(* with c, C depending only on psi.                                           *)
(*                                                                            *)
(* The paper uses two instances: m of order d log d with D = d (d + 1) / 2    *)
(* (the sparse Gram estimate of Proposition 3.1) and m = D                    *)
(* (|W|_op <= C sqrt D for n <= C0 D, Proposition 3.1 and Lemma 3.12).        *)
(*                                                                            *)
(* Planned route: the diagonal part from the norms of the columns; the        *)
(* off-diagonal part sup_u |sum_{i <> j} u_i u_j <w_i, w_j>| over m-sparse    *)
(* unit vectors u by decoupling over a random partition of the indices,       *)
(* conditioning on one part, Bernstein's inequality for the independent       *)
(* subexponential variables <w_i, y> (subgaussian.v, lane A), nets of sparse  *)
(* unit vectors (matrix/nets.v) organised by the level sets of the            *)
(* coordinates of u, and sum_{k <= m} binom n k <= (e n / m)^m. A weaker      *)
(* self-contained substitute that suffices for the paper is acceptable        *)
(* (AGENTS.md); the first report on S3 says which one is used.                *)
(*                                                                            *)
(* - restricted_isometry: the estimate above.                                 *)
(* - For the full matrix, |W|_op <= C sqrt D with high probability when       *)
(*   n <= C0 D, by cutting the columns into O(C0) blocks of at most D.        *)

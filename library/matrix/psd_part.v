(* # The positive part of a symmetric matrix                                  *)
(*                                                                            *)
(* Plan (phase 5, stage 2, item G8 of lane C; names come with the proofs).    *)
(* For a real symmetric matrix A with a spectral decomposition                *)
(* A = P^T diag(d) P, P orthogonal (symmetric_spectral of real_spectral.v),   *)
(* the positive part A_+ = P^T diag((d_i)_+) P is the nearest positive        *)
(* semidefinite matrix to A in the Frobenius norm. It is defined from the     *)
(* decomposition chosen by sym_spectralmx and sym_spectral_diag; the          *)
(* nearest-point property shows that it does not depend on that choice.       *)
(*                                                                            *)
(* Answer to requests/a-to-c.md (stage 2, item 1): G8 handles spectral        *)
(* functions through psd_part, which is equivariant under orthogonal          *)
(* conjugation. goe_rotation.v may state Lemma 5.13 for any F with            *)
(* F (Q W Q^T) = Q F(W) Q^T for every orthogonal Q: psd_part satisfies it,    *)
(* and so does W |-> psd_part (W - w(W) I) for a w(W) that depends only on    *)
(* the spectrum of W (the optimizer of Lemma 5.14).                           *)
(*                                                                            *)
(* - psd_part A: for A symmetric, psd_part A >= 0 and                         *)
(*   |A - psd_part A|_F <= |A - S|_F for every S >= 0, with equality only at  *)
(*   S = psd_part A; psd_part A = P^T diag((d_i)_+) P for every spectral      *)
(*   decomposition; psd_part (Q A Q^T) = Q (psd_part A) Q^T for Q             *)
(*   orthogonal.                                                              *)
(* - Moreau's decomposition of A: A = psd_part A - psd_part (- A) with        *)
(*   <psd_part A, psd_part (- A)> = 0, and |psd_part A|_F^2 =                 *)
(*   sum_i (spec A i)_+^2 with spec of matrix/von_neumann.v (lane A).         *)
(* - psd_part is 1-Lipschitz for the Frobenius norm (the variational          *)
(*   inequality <A - psd_part A, S - psd_part A> <= 0 for S >= 0), hence      *)
(*   continuous and measurable.                                               *)
(* - The shifted positive part psd_part (A - w I): its trace                  *)
(*   sum_i (spec A i - w)_+ and its squared Frobenius norm                    *)
(*   sum_i (spec A i - w)_+^2, continuous in (A, w); these are d m_d and      *)
(*   d s_d of Lemma 5.14 at A = G_d / sqrt d.                                 *)

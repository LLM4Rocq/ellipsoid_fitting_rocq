Section measurable_mxbox.
Context {d} {T : measurableType d} {m n : nat}.

Definition mxbox (A : 'I_m -> 'I_n -> set T) : set 'M[T]_(m, n) :=
  [set M | forall i j, A i j (M i j)].

Definition mxboxes : set (set 'M[T]_(m, n)) :=
  [set mxbox A | A in [set A | forall i j, measurable (A i j)]].

Lemma mxboxT : mxbox (fun _ _ => [set: T]) = [set: 'M[T]_(m, n)].
Proof. by apply/seteqP; split. Qed.

Lemma mxboxI A B : mxbox A `&` mxbox B = mxbox (fun i j => A i j `&` B i j).
Proof.
apply/seteqP; split=> M; first by move=> [MA MB] i j; split; [exact: MA|exact: MB].
by move=> MAB; split=> i j; have [] := MAB i j.
Qed.

Lemma measurable_mxbox A : (forall i j, measurable (A i j)) ->
  measurable (mxbox A).
Proof.
move=> mA.
have -> : mxbox A = \bigcap_(k in [set: 'I_m * 'I_n])
    [set M : 'M[T]_(m, n) | A k.1 k.2 (M k.1 k.2)].
  apply/seteqP; split=> [M MA [i j] _|M MA i j]; first exact: MA.
  exact: (MA (i, j)).
apply: fin_bigcap_measurable; first exact: finite_finset.
move=> [i j] _; have := measurable_mxentry i j measurableT (mA i j).
by rewrite setTI.
Qed.

Lemma measurable_mxboxes : @measurable _ 'M[T]_(m, n) = <<s mxboxes >>.
Proof.
apply/seteqP; split; last first.
  apply: smallest_sub; first exact: sigma_algebra_measurable.
  by move=> _ [A mA <-]; exact: measurable_mxbox.
apply: smallest_sub; first exact: smallest_sigma_algebra.
rewrite -bigcup_seq; apply: bigcup_sub => k _.
case: (mxvec_indexP k) => i j _ [B mB <-]; rewrite setTI.
apply: sub_sigma_algebra.
exists (fun i' j' => if (i', j') == (i, j) then B else [set: T]).
  by move=> i' j'; case: ifP.
apply/seteqP; split=> M /=; rewrite mxvecE.
  by move=> /(_ i j); rewrite eqxx.
by move=> MB i' j'; case: ifPn => // /eqP[-> ->].
Qed.

Lemma setI_closed_mxboxes : setI_closed mxboxes.
Proof.
move=> _ _ [A mA <-] [B mB <-]; rewrite mxboxI.
by exists (fun i j => A i j `&` B i j) => // i j; exact: measurableI.
Qed.

Lemma measure_mxbox_unique (R : realType)
    (mu1 mu2 : {measure set 'M[T]_(m, n) -> \bar R}) :
  (mu1 [set: 'M[T]_(m, n)] < +oo)%E ->
  (forall A, (forall i j, measurable (A i j)) -> mu1 (mxbox A) = mu2 (mxbox A)) ->
  forall X, measurable X -> mu1 X = mu2 X.
Proof.
move=> mu1T mu12.
apply: (measure_unique mxboxes (fun=> [set: 'M[T]_(m, n)])).
- exact: measurable_mxboxes.
- exact: setI_closed_mxboxes.
- by move=> _; rewrite -mxboxT; exists (fun _ _ => [set: T]).
- by rewrite bigcup_const.
- by move=> _ [A mA <-]; exact: mu12.
- by move=> _.
Qed.

End measurable_mxbox.

Section measurable_rowbox.
Context {d} {T : measurableType d} {n : nat}.

Lemma rowboxE (A : 'I_n -> set T) :
  [set x : 'rV[T]_n | forall j, A j (x 0 j)] = mxbox (fun _ j => A j).
Proof.
by apply/seteqP; split=> x xA => [i j|j]; [rewrite (ord1 i)|]; exact: xA.
Qed.

Lemma measurable_rowbox (A : 'I_n -> set T) : (forall j, measurable (A j)) ->
  measurable [set x : 'rV[T]_n | forall j, A j (x 0 j)].
Proof. by move=> mA; rewrite rowboxE; apply: measurable_mxbox. Qed.

Lemma measure_rowbox_unique (R : realType)
    (mu1 mu2 : {measure set 'rV[T]_n -> \bar R}) :
  (mu1 [set: 'rV[T]_n] < +oo)%E ->
  (forall A : 'I_n -> set T, (forall j, measurable (A j)) ->
    mu1 [set x | forall j, A j (x 0 j)] = mu2 [set x | forall j, A j (x 0 j)]) ->
  forall X, measurable X -> mu1 X = mu2 X.
Proof.
move=> mu1T mu12; apply: measure_mxbox_unique => // A mA.
have -> : mxbox A = [set x : 'rV[T]_n | forall j, A 0 j (x 0 j)].
  by rewrite rowboxE; apply/seteqP; split=> x xA i j; rewrite (ord1 i); exact: xA.
by apply: mu12 => j; exact: mA.
Qed.

End measurable_rowbox.


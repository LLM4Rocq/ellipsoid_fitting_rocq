(* # Measurable structure on matrices                                         *)
(*                                                                            *)
(* A matrix with entries in a measurable space is measurable for the          *)
(* sigma-algebra generated by its entries, as tuples are in                   *)
(* MathComp-Analysis (measurable_structure.v). Row vectors 'rV[T]_n and       *)
(* column vectors 'cV[T]_n are matrices, so they get this structure too.      *)
(* The boxes generate it and are closed under intersection, so two finite     *)
(* measures that agree on the boxes agree (measure_mxbox_unique). For real    *)
(* matrices it contains the open sets, so continuous functions are            *)
(* measurable (continuous_measurable_mx).                                     *)
(*                                                                            *)
(* ```                                                                        *)
(* measure_matrix_display d == display of the sigma-algebra of the matrices   *)
(*                             with entries in a space of display d           *)
(*                             'M[T]_(m, n) is equipped with a measurableType *)
(*                             structure generated by the entries             *)
(*                 mxbox A == the box of the matrices M such that M i j is in *)
(*                            A i j for all i and j; for a row vector x, the  *)
(*                            box [set x | forall j, A j (x 0 j)] is used     *)
(*                            directly (rowboxE)                              *)
(*               mxboxes T == the boxes mxbox A with measurable sides A i j   *)
(* ```                                                                        *)
(*                                                                            *)

Section measurable_matrix.
Context {d} {T : sigmaRingType d} (m n : nat).

Let entry (k : 'I_(m * n)) (A : 'M[T]_(m, n)) : T := mxvec A 0 k.

Let matrix_set0 : g_sigma_preimage entry set0.
Proof. exact: sigma_algebra0. Qed.

Let matrix_setC A : g_sigma_preimage entry A -> g_sigma_preimage entry (~` A).
Proof. exact: sigma_algebraC. Qed.

Let matrix_bigcup (F : nat -> set 'M[T]_(m, n)) :
  (forall i, g_sigma_preimage entry (F i)) ->
  g_sigma_preimage entry (\bigcup_i (F i)).
Proof. exact: sigma_algebra_bigcup. Qed.

(* HB declares canonical projections that the structure of T already
   provides, as for tuples; the warning says so. *)
Set Warnings "-redundant-canonical-projection".
HB.instance Definition _ := @isMeasurable.Build (measure_matrix_display d)
  'M[T]_(m, n) (g_sigma_preimage entry) matrix_set0 matrix_setC matrix_bigcup.

End measurable_matrix.
Set Warnings "redundant-canonical-projection".

Section measurable_entries.
Context {d d'} {T : measurableType d} {U : measurableType d'} {m n : nat}.
Implicit Types f : U -> 'M[T]_(m, n).

Lemma measurable_mxentry (i : 'I_m) (j : 'I_n) :
  measurable_fun [set: 'M[T]_(m, n)] (fun A => A i j).
Proof.
move=> _ Y mY; rewrite setTI; apply: sub_sigma_algebra => /=.
rewrite -bigcup_seq/=; exists (mxvec_index i j) => /=.
  by rewrite mem_index_enum.
by exists Y => //; rewrite setTI; apply/funext => A /=; rewrite mxvecE.
Qed.

Lemma measurable_fun_mxP f : measurable_fun [set: U] f <->
  forall i j, measurable_fun [set: U] (fun x => f x i j).
Proof.
split=> [mf i j|mf]; first exact: measurableT_comp (measurable_mxentry i j) mf.
have : g_sigma_preimage (fun k => (fun A : 'M[T]_(m, n) => mxvec A 0 k) \o f)
    `<=` measurable.
  apply: smallest_sub; first exact: sigma_algebra_measurable.
  rewrite -bigcup_seq; apply: bigcup_sub => k _.
  case: (mxvec_indexP k) => i j _ [B mB <-]; rewrite setTI.
  have := mf i j measurableT B mB; rewrite setTI.
  by congr measurable; apply/funext => x /=; rewrite mxvecE.
rewrite g_sigma_preimage_comp => fmeas _ Y mY.
by rewrite setTI -[_ @^-1` _]setTI; apply: fmeas; exists Y.
Qed.

Lemma measurable_matrix (h : 'I_m -> 'I_n -> U -> T) :
  (forall i j, measurable_fun [set: U] (h i j)) ->
  measurable_fun [set: U] (fun x => \matrix_(i, j) h i j x).
Proof.
move=> mh; apply/measurable_fun_mxP => i j.
by under eq_fun do rewrite mxE; exact: mh.
Qed.

End measurable_entries.


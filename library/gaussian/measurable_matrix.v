Section continuous_measurable_mx.
Context {R : realType} {m n : nat}.

Let rbox (q : 'M[rat]_(m, n)) (r : rat) : set 'M[R]_(m, n) :=
  mxbox (fun i j => [set x : R | `|ratr (q i j) - x| < ratr r]).

Let measurable_rbox q r : measurable (rbox q r).
Proof.
apply: measurable_mxbox => i j.
have -> : [set x : R | `|ratr (q i j) - x| < ratr r] =
    `](ratr (q i j) - ratr r), (ratr (q i j) + ratr r)[%classic.
  by apply/seteqP; split=> x /=; rewrite in_itv/= ltr_distlC.
exact: measurable_itv.
Qed.

Lemma open_measurable_mx (V : set 'M[R]_(m, n)) : open V -> measurable V.
Proof.
move=> oV.
pose F (p : 'M[rat]_(m, n) * rat) :=
  if `[< rbox p.1 p.2 `<=` V >] then rbox p.1 p.2 else set0.
suff -> : V = \bigcup_p F p.
  apply: countable_bigcupT_measurable; first exact: countableP.
  move=> p; rewrite /F; case: asboolP => _; last exact: measurable0.
  exact: measurable_rbox.
apply/seteqP; split=> [M VM|M [p _]]; last first.
  by rewrite /F; case: asboolP => [pV /pV//|_].
have /nbhs_ballP[e /= e0 eV] := oV M VM.
have [r [r0 re]] : exists r : rat, 0 < ratr r :> R /\ ratr r < e / 2.
  have e20 : 0 < e / 2 :> R by rewrite divr_gt0.
  have [r] := rat_in_itvoo e20.
  by rewrite in_itv/= => /andP[? ?]; exists r.
have qM (ij : 'I_m * 'I_n) : exists q : rat, `|ratr q - M ij.1 ij.2| < ratr r.
  have lt : M ij.1 ij.2 - ratr r < M ij.1 ij.2 + ratr r by rewrite ltrD2l gtrN.
  have [q] := rat_in_itvoo lt.
  by rewrite in_itv/= -ltr_distlC distrC => ?; exists q.
have [qf qfP] := choice qM.
pose q : 'M[rat]_(m, n) := \matrix_(i, j) qf (i, j).
have Mq : rbox q r M by move=> i j /=; rewrite mxE; exact: (qfP (i, j)).
have qV : rbox q r `<=` V.
  move=> N Nq; apply: eV; split => // i j.
  have := Nq i j; have := Mq i j; rewrite /= => h1 h2.
  rewrite /ball /= (le_lt_trans (ler_distD (ratr (q i j)) _ _))//.
  rewrite distrC (lt_le_trans (ltrD h1 h2))// -mulr2n -mulr_natr.
  by rewrite -ler_pdivlMr// ltW.
by exists (q, r) => //; rewrite /F /=; case: asboolP => // /(_ qV) [].
Qed.

Lemma continuous_measurable_mx (f : 'M[R]_(m, n) -> R) :
  continuous f -> measurable_fun [set: 'M[R]_(m, n)] f.
Proof.
move=> /continuousP cf; apply: (measurability _ (RGenOpens.measurableE R)).
move=> _ [_ [a [b ->] <-]]; rewrite setTI.
by apply: open_measurable_mx; apply: cf; exact: interval_open.
Qed.

End continuous_measurable_mx.

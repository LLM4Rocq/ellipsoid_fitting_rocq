Lemma mxdot_characterization (R : realType) m n (A B : 'M[R]_(m, n)) :
  mxdot A B = \sum_i \sum_j A i j * B i j.
Proof. by []. Qed.

Lemma frobenius_characterization (R : realType) m n (A : 'M[R]_(m, n)) :
  frobenius A = Num.sqrt (\sum_i \sum_j A i j ^+ 2).
Proof.
by rewrite /frobenius mxdot_characterization; under eq_bigr do
  under eq_bigr do rewrite -expr2.
Qed.

Lemma opnorm_characterization (R : realType) m n (A : 'M[R]_(m, n)) :
  opnorm A =
  sup [set frobenius (A *m x) | x in [set x : 'cV[R]_n | frobenius x <= 1]].
Proof. by []. Qed.

Lemma psdmx_characterization (R : realType) n (A : 'M[R]_n) :
  psdmx A <-> A \is symmetricmx /\ forall x : 'cV[R]_n, 0 <= (x^T *m A *m x) 0 0.
Proof.
by split => -[As Ap]; split => // x; have := Ap x;
  rewrite mxdot_colE mulmxA.
Qed.

Lemma goe_mx_characterization (R : realType) d (a : 'rV[R]_(d * d)) :
  goe_mx a = (Num.sqrt (2 * d%:R))^-1 *: (vec_mx a + (vec_mx a)^T).
Proof. by []. Qed.

Lemma matrix_measurable_characterization {dT} (T : measurableType dT) m n :
  @measurable _ 'M[T]_(m, n) =
  <<s [set [set M : 'M[T]_(m, n) | forall i j, A i j (M i j)] |
       A in [set A : 'I_m -> 'I_n -> set T | forall i j, measurable (A i j)]] >>.
Proof. exact: measurable_mxboxes. Qed.

Lemma gauss_characterization (R : realType) n (A : 'I_n -> set R) :
  (forall i, measurable (A i)) ->
  gauss n [set x : 'rV[R]_n | forall i, A i (x 0 i)] =
    (\prod_(i < n) normal_prob 0 1 (A i))%E.
Proof. exact: gauss_box. Qed.

Lemma gauss_determined (R : realType) n (P : {measure set 'rV[R]_n -> \bar R}) :
  (forall A : 'I_n -> set R, (forall i, measurable (A i)) ->
     P [set x : 'rV[R]_n | forall i, A i (x 0 i)] =
       (\prod_(i < n) normal_prob 0 1 (A i))%E) ->
  forall X, measurable X -> P X = gauss n X.
Proof. exact: gauss_unique. Qed.

(* The library definitions that the frozen statements of applications/
   unfold to, characterized by properties that determine them (phase 12,
   the freeze of batch 1; AGENTS.md, section Phase 12, step 0, item 4).

   Each lemma states its property in this file, with MathComp's and
   MathComp-Analysis's vocabulary, and make check compiles the file: a
   change of a definition that breaks its property makes make check fail,
   while a change of its implementation that keeps the property is allowed.
   scripts/check_sources.py fixes the code of this file
   (APPLICATIONS_DEFINITIONS_CHECK).

   - mxdot (matrix/euclidean.v): the sum of the products of the entries.
   - frobenius (matrix/euclidean.v): the square root of the sum of the
     squares of the entries.
   - opnorm (matrix/opnorm.v): the supremum of frobenius (A x) over the
     columns x with frobenius x <= 1.
   - psdmx (matrix/psd_part.v): symmetric, with x^T A x >= 0 for every
     column x.
   - goe_mx (random_matrix/goe.v): (A + A^T) / sqrt (2 d), A = vec_mx a.
   - The measurable structure of matrices, hence of row vectors
     (gaussian/measurable_matrix.v): the sigma-algebra generated by the
     boxes whose sides are measurable sets of R.
   - gauss (gaussian/gauss.v): the box with measurable sides A_0, ...,
     A_(n-1) has measure prod_i normal_prob 0 1 (A_i); and these values
     determine the measure: every measure with them agrees with gauss n on
     every measurable set. *)


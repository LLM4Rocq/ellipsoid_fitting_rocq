(* The finite Gaussian product law: the law of d independent standard normal
   coordinates, as a probability measure of MathComp-Analysis on the
   measurable type of d-tuples of reals, built by recursion on d from the
   one-dimensional law gaussian_law of GaussianProbabilityDefinitions. This
   module contains definitions and the proofs that construct them; every
   proof is named below and is a construction step.

   Carrier. The d-th law lives on d.-tuple (measurableTypeR R), MathComp's
   tuples of length d over the Borel copy of Stdlib's R, which carry the
   product sigma-algebra generated by the coordinates tnth (section
   measurable_tuple of measure_theory/measurable_structure.v). A tuple x is
   read as the coordinate list tval x : list R (first coordinate first), the
   list that gaussian_iterated_expectation integrates
   (GaussianProductDefinitions); the i-th coordinate is List.nth i (tval x) 0.

   Construction, by recursion on d.
   - d = 0: the Dirac law at the empty tuple (MathComp's dirac, a probability
     by the instance of probability_measure.v).
   - d + 1: the pair (x, xs) of a real and a d-tuple has the product law
     gaussian_pair_probability gaussian_law (gaussian_product_law d), which is
     MathComp's product_measure1 of the two laws (the first factor integrated
     outermost, as gaussian_iterated_expectation integrates the first list
     coordinate outermost); its image under the measurable map
     (x, xs) |-> x :: xs is
     MathComp's distribution of that map, a probability by the instance of
     probability_theory/random_variable.v.

   Proofs inside this module, all of them construction steps that MathComp
   requires to type the objects:
   1. gaussian_pair_probability_setT: the product of two probabilities has
      mass one, from product_measure1E on the rectangle setT x setT; it makes
      product_measure1 P Q a probability (Measure_isProbability), so that it
      can be the second factor of the next product, which must be
      sigma-finite.
   2. gaussian_cons_tuple_measurable: the map (x, xs) |-> x :: xs is
      measurable, from measurable_cons, measurable_fst and measurable_snd of
      MathComp; it packages the map as a measurable function ({mfun}), which
      distribution requires.
   No other proof is made here. The one-dimensional law is used as it is:
   normal_prob 0 1 carries its probability structure. R_scope is opened
   last; the constructions are
   written in MathComp's scopes where they must be, and every 0 and 1 of the
   one-dimensional law is Stdlib's. *)
From Stdlib Require Import Reals List.
From HB Require Import structures.
From mathcomp Require Import all_ssreflect_compat ssralg ssrnum.
From mathcomp Require Import boolp classical_sets functions reals Rstruct.
From mathcomp Require Import topology Rstruct_topology.
From mathcomp Require Import ereal measure lebesgue_measure lebesgue_integral.
From mathcomp Require Import probability normal_distribution.
From EllipsoidFitting Require Import AnalysisIntegralDefinitions GaussianDefinitions GaussianProbabilityDefinitions.
Open Scope R_scope.

(* The one-dimensional law with its probability structure made explicit. *)
Definition gaussian_law_probability : probability (measurableTypeR R) R := normal_prob 0 1.

Section gaussian_pair_probability.
Local Open Scope ereal_scope.
Context {d1 d2 : measure_display} {T1 : measurableType d1} {T2 : measurableType d2}.
Variables (P : probability T1 R) (Q : probability T2 R).

(* Construction proof 1: the product of two probabilities has mass one. *)
Let gaussian_pair_probability_setT : (P \x Q) [set: T1 * T2] = 1.
Proof.
rewrite -setXTT product_measure1E//.
apply: (@eq_trans _ _ (1 * 1)); last exact: mule1.
by congr (_ * _); exact: probability_setT.
Qed.

HB.instance Definition _ :=
  Measure_isProbability.Build _ _ _ (P \x Q) gaussian_pair_probability_setT.

Definition gaussian_pair_probability : probability (T1 * T2)%type R := P \x Q.
End gaussian_pair_probability.

Section gaussian_cons_tuple.
Variable d : nat.
Local Notation T := (measurableTypeR R).

(* The map (x, xs) |-> x :: xs from a pair to a tuple of length d + 1. *)
Definition gaussian_cons_tuple (p : T * d.-tuple T) : d.+1.-tuple T :=
  [the d.+1.-tuple T of p.1 :: p.2].

(* Construction proof 2: that map is measurable. *)
Lemma gaussian_cons_tuple_measurable : measurable_fun [set: T * d.-tuple T] gaussian_cons_tuple.
Proof. exact: (measurable_cons measurable_fst measurable_snd). Qed.

HB.instance Definition _ :=
  isMeasurableFun.Build _ _ _ _ gaussian_cons_tuple gaussian_cons_tuple_measurable.
End gaussian_cons_tuple.

(* The law of d independent standard normal coordinates. *)
Fixpoint gaussian_product_law (d : nat) : probability (d.-tuple (measurableTypeR R)) R :=
  match d return probability (d.-tuple (measurableTypeR R)) R with
  | O => dirac ([tuple] : 0.-tuple (measurableTypeR R))
  | S d' => distribution (gaussian_pair_probability gaussian_law_probability (gaussian_product_law d'))
              (gaussian_cons_tuple d')
  end.

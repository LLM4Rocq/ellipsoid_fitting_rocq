(* Integrals of real functions on a segment and on the whole real line,
   stated with the Lebesgue integral of MathComp-Analysis. The module also
   defines continuity_2d_pt, the joint continuity of a function of two real
   variables, which the Fubini statements on rectangles take as their
   hypothesis. This module contains definitions only.

   The measure is lebesgue_measure, defined on the Borel sets of R (the
   sigma-algebra generated by the intervals). Rintegral lebesgue_measure D f
   is MathComp's real-valued integral, fine (\int[lebesgue_measure]_(x in D)
   (f x)%:E), where fine sends +oo and -oo to 0. The measure is defined on
   measurableTypeR R, a copy of R that carries the Borel sets. Stdlib's R has
   no measurable structure of its own, so a statement about the
   measurability of f : R -> R casts both the domain and the function:
   measurable_fun (setT : set (measurableTypeR R))
     (f : measurableTypeR R -> measurableTypeR R).

   Measurability convention. MathComp's mu.-integrable D g means that g is
   measurable on D and that the integral of |g| over D is finite. The
   integrability predicates below therefore include Borel measurability of f.

   Values off the domain. When f is measurable but its absolute value has an
   infinite integral, the extended integral of f is +oo or -oo, and the
   real-valued integrals below return 0. When f is not measurable, they return
   whatever fine gives on MathComp's integral of f, which carries no intended
   meaning. Statements use the values together with an integrability
   hypothesis or conclusion.

   Comparison with the Riemann integral.
   - On a segment, the Lebesgue and the Riemann integrals agree on a Borel
     measurable, Riemann integrable function. The Lebesgue predicate also
     accepts some unbounded functions, and rejects Riemann integrable
     functions that are not Borel measurable. Continuous functions satisfy
     both.
   - Over the line, the improper Riemann integral, the limit of the Riemann
     integrals on [a, b] as a tends to -oo and b to +oo independently, exists
     for some functions whose absolute value is not integrable. The Lebesgue
     integral over the line requires absolute integrability. The two agree
     on a Borel measurable function that is Riemann integrable on every
     segment and whose absolute value has a finite Lebesgue integral. *)

From Stdlib Require Import Reals.
From mathcomp Require Import all_ssreflect_compat ssralg ssrnum interval.
From mathcomp Require Import classical_sets reals Rstruct.
From mathcomp Require Import topology Rstruct_topology.
From mathcomp Require Import ereal measure lebesgue_measure lebesgue_integral.
Open Scope R_scope.

(* The oriented integral of f from a to b: the integral over the closed
   interval [a, b] when a <= b, and minus the integral over [b, a]
   otherwise, so that swapping a and b changes its sign. *)
Definition oriented_integral (f : R -> R) (a b : R) : R :=
  if Rle_dec a b then Rintegral lebesgue_measure `[a, b]%classic f
  else - Rintegral lebesgue_measure `[b, a]%classic f.

(* f is Lebesgue integrable on the segment with end points a and b, in either
   order. *)
Definition segment_integrable (f : R -> R) (a b : R) : Prop :=
  lebesgue_measure.-integrable `[Rmin a b, Rmax a b]%classic (EFin \o f).

(* f is integrable on the segment between a and b and its oriented integral
   from a to b is l. *)
Definition oriented_has_integral (f : R -> R) (a b l : R) : Prop :=
  segment_integrable f a b /\ oriented_integral f a b = l.

(* The integral of f over the whole real line. *)
Definition whole_line_integral (f : R -> R) : R :=
  Rintegral lebesgue_measure setT f.

(* f is Lebesgue integrable on the whole real line. *)
Definition whole_line_integrable (f : R -> R) : Prop :=
  lebesgue_measure.-integrable setT (EFin \o f).

(* f is integrable on the whole real line and its integral is l. *)
Definition whole_line_has_integral (f : R -> R) (l : R) : Prop :=
  whole_line_integrable f /\ whole_line_integral f = l.

(* Joint continuity of f at the point (x, y): the continuity at (x, y) of
   p |-> f p.1 p.2 for the product topology of R * R. Equivalently, for
   every eps > 0 there is a delta > 0 such that Rabs (f u v - f x y) < eps
   whenever Rabs (u - x) < delta and Rabs (v - y) < delta: the open squares
   centred at (x, y) are the balls of MathComp's distance on R * R, the
   maximum of the distances of the coordinates, and they form a base of the
   neighbourhoods of (x, y). *)
Definition continuity_2d_pt (f : R -> R -> R) (x y : R) : Prop :=
  {for (x, y), continuous (fun p : R * R => f p.1 p.2)}.

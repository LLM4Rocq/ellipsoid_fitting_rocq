(* Integrals of real functions on a segment and on the whole real line,
   stated with the Lebesgue integral of MathComp-Analysis. They replace
   Coquelicot's RInt, is_RInt and ex_RInt on a segment, and RInt_gen,
   is_RInt_gen and ex_RInt_gen over the filters (Rbar_locally m_infty) and
   (Rbar_locally p_infty). The module also defines continuity_2d_pt, the
   joint continuity of a function of two real variables, which the Fubini
   statements on rectangles take as their hypothesis. It keeps Coquelicot's
   name and says the same thing. This module contains definitions only.

   The measure is lebesgue_measure, defined on the Borel sets of R (the
   sigma-algebra generated by the intervals). Rintegral lebesgue_measure D f
   is MathComp's real-valued integral, fine (\int[lebesgue_measure]_(x in D)
   (f x)%:E), where fine sends +oo and -oo to 0. The measure is defined on
   measurableTypeR R, a copy of R that carries the Borel sets. Stdlib's R has
   no measurable structure of its own, so a statement about the
   measurability of f : R -> R casts both the domain and the function:
   measurable_fun (setT : set (measurableTypeR R))
     (f : measurableTypeR R -> measurableTypeR R).

   Measurability convention. MathComp's mu.-integrable D g means that g is
   measurable on D and that the integral of |g| over D is finite. The
   integrability predicates below therefore include Borel measurability of f.

   Values off the domain. When f is measurable but its absolute value has an
   infinite integral, the extended integral of f is +oo or -oo, and the
   real-valued integrals below return 0. When f is not measurable, they return
   whatever fine gives on MathComp's integral of f, which carries no intended
   meaning. Statements use the values together with an integrability
   hypothesis or conclusion, as they did with Coquelicot, whose values off the
   domain were unspecified.

   Differences in meaning with Coquelicot (differences 3 and 4 of
   analysis/README.md).
   - Coquelicot's integral on a segment is the Riemann integral. On a Borel
     measurable, Riemann integrable function the two integrals agree. The
     Lebesgue predicate also accepts some unbounded functions, and rejects
     Riemann integrable functions that are not Borel measurable. Continuous
     functions satisfy both.
   - Coquelicot's integral over the line is the limit of Riemann integrals on
     [a, b] as a tends to -oo and b to +oo independently. It exists for some
     functions whose absolute value is not integrable. The Lebesgue integral
     over the line requires absolute integrability. The two agree on a Borel
     measurable function that is Riemann integrable on every segment and
     whose absolute value has a finite Lebesgue integral. *)

From Stdlib Require Import Reals.
From mathcomp Require Import all_ssreflect_compat ssralg ssrnum interval.
From mathcomp Require Import classical_sets reals Rstruct.
From mathcomp Require Import topology Rstruct_topology.
From mathcomp Require Import ereal measure lebesgue_measure lebesgue_integral.
Open Scope R_scope.

(* The oriented integral of f from a to b, in place of Coquelicot's RInt f a b.
   It is the integral over the closed interval [a, b] when a <= b, and minus
   the integral over [b, a] otherwise, so that swapping a and b changes its
   sign, as for RInt. *)
Definition oriented_integral (f : R -> R) (a b : R) : R :=
  if Rle_dec a b then Rintegral lebesgue_measure `[a, b]%classic f
  else - Rintegral lebesgue_measure `[b, a]%classic f.

(* f is Lebesgue integrable on the segment with end points a and b, in either
   order, in place of Coquelicot's ex_RInt f a b. *)
Definition segment_integrable (f : R -> R) (a b : R) : Prop :=
  lebesgue_measure.-integrable `[Rmin a b, Rmax a b]%classic (EFin \o f).

(* f is integrable on the segment between a and b and its oriented integral
   from a to b is l, in place of Coquelicot's is_RInt f a b l. *)
Definition oriented_has_integral (f : R -> R) (a b l : R) : Prop :=
  segment_integrable f a b /\ oriented_integral f a b = l.

(* The integral of f over the whole real line, in place of Coquelicot's
   RInt_gen f (Rbar_locally m_infty) (Rbar_locally p_infty). *)
Definition whole_line_integral (f : R -> R) : R :=
  Rintegral lebesgue_measure setT f.

(* f is Lebesgue integrable on the whole real line, in place of Coquelicot's
   ex_RInt_gen f (Rbar_locally m_infty) (Rbar_locally p_infty). *)
Definition whole_line_integrable (f : R -> R) : Prop :=
  lebesgue_measure.-integrable setT (EFin \o f).

(* f is integrable on the whole real line and its integral is l, in place of
   Coquelicot's
   is_RInt_gen f (Rbar_locally m_infty) (Rbar_locally p_infty) l. *)
Definition whole_line_has_integral (f : R -> R) (l : R) : Prop :=
  whole_line_integrable f /\ whole_line_integral f = l.

(* Joint continuity of f at the point (x, y), in place of Coquelicot's
   continuity_2d_pt f x y and under the same name. It is the continuity at
   (x, y) of p |-> f p.1 p.2 for the product topology of R * R. Coquelicot's
   definition says: for every eps > 0 there is a delta > 0 such that
   Rabs (f u v - f x y) < eps whenever Rabs (u - x) < delta and
   Rabs (v - y) < delta. The open squares centred at (x, y) are the balls of
   MathComp's distance on R * R, the maximum of the distances of the
   coordinates, and they form a base of the neighbourhoods of (x, y). So the
   two definitions are equivalent. *)
Definition continuity_2d_pt (f : R -> R -> R) (x y : R) : Prop :=
  {for (x, y), continuous (fun p : R * R => f p.1 p.2)}.

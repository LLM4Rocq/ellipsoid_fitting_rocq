(* Port of theories/GaussianExpectation.v from Coquelicot to MathComp-Analysis.

   Every lemma of the original keeps its name and its arguments, in the same
   order. The statements use the vocabulary of AnalysisIntegralDefinitions:
   ex_RInt_gen f (Rbar_locally m_infty) (Rbar_locally p_infty) becomes
   whole_line_integrable f, and is_RInt_gen f (Rbar_locally m_infty)
   (Rbar_locally p_infty) l becomes whole_line_has_integral f l, the
   Lebesgue integral over the line (difference 4 of analysis/README.md).
   gaussian_integral, gaussian_has_integral, gaussian_integral_exists and
   gaussian_mass follow the ported GaussianDefinitions. The arithmetic in
   every statement is Stdlib's, as in the original.

   Statements that change form.

   1. gaussian_has_integral_constant, gaussian_integral_constant,
      gaussian_expectation_constant, gaussian_density_normalized and
      gaussian_has_integral_uniform_bound: the hypothesis
      ex_RInt_gen gaussian_kernel (Rbar_locally m_infty) (Rbar_locally p_infty)
      becomes whole_line_integrable gaussian_kernel.

   2. gaussian_density_normalized and gaussian_density_mass_one: the
      conclusion is_RInt_gen gaussian_density (Rbar_locally m_infty)
      (Rbar_locally p_infty) 1 becomes whole_line_has_integral
      gaussian_density 1, as in the restated clause 2 of the challenge
      ellipsoid_gaussian (analysis/challenges/ellipsoid_gaussian).

   3. gaussian_endpoints_ordered: Coquelicot's product filter
      filter_prod (Rbar_locally m_infty) (Rbar_locally p_infty) becomes
      MathComp's filter_prod (-oo%R) (+oo%R) on R * R. Both are the filter
      generated by the products Q `*` P with Q a neighbourhood of -oo and P
      a neighbourhood of +oo, so the statement says the same thing. The
      proofs of this module no longer use it, because the Lebesgue integral
      over the line is not a limit along that filter; it is kept for the
      name.

   What changes in the proofs. With Coquelicot, gaussian_integral_exists f
   was by definition exists l, gaussian_has_integral f l. In the port it is
   the Lebesgue integrability of x |-> f x * gaussian_kernel x, and
   gaussian_has_integral f l is that together with gaussian_integral f = l.
   So gaussian_integral_unique and gaussian_integral_correct follow from
   the definitions, and the proofs of gaussian_integral_exists_scale, _add
   and _sub no longer destruct an existential. The integrability and the
   value of scaled, added and subtracted integrands come from MathComp's
   integrableD, integrableB, RintegralD and RintegralB, and from
   fubini_integrable_scale and fubini_integral_scale_l of
   GaussianFubiniLebesgue. The bounds come from fubini_Rintegral_bound,
   fubini_Rintegral_abs_le and MathComp's Rintegral_ge0; they replace
   Coquelicot's RInt_gen_norm, which needed gaussian_endpoints_ordered.
   In gaussian_expectation_absolute_bound the hypothesis
   gaussian_absolutely_integrable f is kept but no longer used: with the
   Lebesgue integral it follows from gaussian_integral_exists f.

   New lemmas, for the importers that used the old definition of
   gaussian_integral_exists as an existential (they wrote exists l and
   destructed [l Hl]):
   - gaussian_has_integral_exists f l: gaussian_has_integral f l implies
     gaussian_integral_exists f;
   - gaussian_integral_exists_iff f: gaussian_integral_exists f is
     equivalent to exists l, gaussian_has_integral f l, which was the
     definition in theories/;
   - gaussian_integral_exists_constant c: the constant c has a Gaussian
     integral. Importers proved it with
     exists (c * gaussian_mass); apply gaussian_has_integral_constant.

   The original imported Classical_Prop; its proofs did not use it. The
   port does not import it, and the assumptions of the module are the
   seven axioms of analysis/README.md. *)

From Stdlib Require Import Reals Lia Lra Psatz.
From EllipsoidFitting Require Import AnalysisBridge2.
From EllipsoidFitting Require Import AnalysisIntegralDefinitions GaussianDefinitions.
From EllipsoidFitting Require Import GaussianKernel GaussianMass GaussianFubiniLebesgue.
Local Open Scope classical_set_scope.
Open Scope R_scope.

Lemma gaussian_integral_unique f l :
  gaussian_has_integral f l -> gaussian_integral f = l.
Proof. by move=> [_ Hl]. Qed.

Lemma gaussian_integral_correct f :
  gaussian_integral_exists f -> gaussian_has_integral f (gaussian_integral f).
Proof. by move=> Hf; split. Qed.

Lemma gaussian_has_integral_ext f g l :
  (forall x, f x = g x) ->
  gaussian_has_integral f l -> gaussian_has_integral g l.
Proof.
  move=> Hfg Hf.
  have -> : g = f by apply/funext => x; rewrite Hfg.
  exact Hf.
Qed.

Lemma gaussian_has_integral_scale f l c :
  gaussian_has_integral f l ->
  gaussian_has_integral (fun x => c * f x) (c * l).
Proof.
  move=> [Hi Hl].
  have E : (fun x => c * f x * gaussian_kernel x) =
      (fun x => c * (f x * gaussian_kernel x)).
  { apply/funext => x; ring. }
  rewrite /gaussian_has_integral /whole_line_has_integral E.
  split.
  - exact: (fubini_integrable_scale setT _ c measurableT Hi).
  - rewrite (fubini_integral_scale_l _ c Hi).
    by unfold gaussian_integral in Hl; rewrite Hl.
Qed.

Lemma gaussian_has_integral_add f g lf lg :
  gaussian_has_integral f lf -> gaussian_has_integral g lg ->
  gaussian_has_integral (fun x => f x + g x) (lf + lg).
Proof.
  move=> [Hf Hlf] [Hg Hlg].
  have E : (fun x => (f x + g x) * gaussian_kernel x) =
      (fun x => f x * gaussian_kernel x + g x * gaussian_kernel x).
  { apply/funext => x; ring. }
  rewrite /gaussian_has_integral /whole_line_has_integral E.
  split.
  - apply: (eq_integrable measurableT _ _ _ (integrableD measurableT Hf Hg)).
    by move=> y _ /=; rewrite -EFinD -RplusE.
  - rewrite /whole_line_integral (RintegralD measurableT Hf Hg).
    unfold gaussian_integral, whole_line_integral in Hlf, Hlg.
    by rewrite Hlf Hlg -RplusE.
Qed.

Lemma gaussian_has_integral_sub f g lf lg :
  gaussian_has_integral f lf -> gaussian_has_integral g lg ->
  gaussian_has_integral (fun x => f x - g x) (lf - lg).
Proof.
  move=> [Hf Hlf] [Hg Hlg].
  have E : (fun x => (f x - g x) * gaussian_kernel x) =
      (fun x => f x * gaussian_kernel x - g x * gaussian_kernel x).
  { apply/funext => x; ring. }
  rewrite /gaussian_has_integral /whole_line_has_integral E.
  split.
  - apply: (eq_integrable measurableT _ _ _ (integrableB measurableT Hf Hg)).
    by move=> y _ /=; rewrite -EFinB -RminusE.
  - rewrite /whole_line_integral (RintegralB measurableT Hf Hg).
    unfold gaussian_integral, whole_line_integral in Hlf, Hlg.
    by rewrite Hlf Hlg -RminusE.
Qed.

Lemma gaussian_integral_scale f c :
  gaussian_integral_exists f ->
  gaussian_integral (fun x => c * f x) = c * gaussian_integral f.
Proof.
  intro Hf; apply gaussian_integral_unique.
  apply gaussian_has_integral_scale; apply gaussian_integral_correct; exact Hf.
Qed.

Lemma gaussian_integral_add f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_integral (fun x => f x + g x) = gaussian_integral f + gaussian_integral g.
Proof.
  intros Hf Hg; apply gaussian_integral_unique.
  apply gaussian_has_integral_add; apply gaussian_integral_correct; assumption.
Qed.

Lemma gaussian_integral_sub f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_integral (fun x => f x - g x) = gaussian_integral f - gaussian_integral g.
Proof.
  intros Hf Hg; apply gaussian_integral_unique.
  apply gaussian_has_integral_sub; apply gaussian_integral_correct; assumption.
Qed.

Lemma gaussian_expectation_scale f c :
  gaussian_integral_exists f ->
  gaussian_expectation (fun x => c * f x) = c * gaussian_expectation f.
Proof.
  intro Hf; unfold gaussian_expectation; rewrite (gaussian_integral_scale f c Hf).
  unfold Rdiv; ring.
Qed.

Lemma gaussian_expectation_add f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_expectation (fun x => f x + g x) = gaussian_expectation f + gaussian_expectation g.
Proof.
  intros Hf Hg; unfold gaussian_expectation; rewrite (gaussian_integral_add f g Hf Hg).
  unfold Rdiv; ring.
Qed.

Lemma gaussian_expectation_sub f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_expectation (fun x => f x - g x) = gaussian_expectation f - gaussian_expectation g.
Proof.
  intros Hf Hg; unfold gaussian_expectation; rewrite (gaussian_integral_sub f g Hf Hg).
  unfold Rdiv; ring.
Qed.

(* Coquelicot's filter_prod (Rbar_locally m_infty) (Rbar_locally p_infty)
   becomes MathComp's filter_prod (-oo%R) (+oo%R) (header, item 3). *)
Lemma gaussian_endpoints_ordered :
  filter_prod (-oo%R : set_system R) (+oo%R : set_system R)
    (fun ab : R * R => fst ab <= snd ab).
Proof.
  exists ([set a : R | a < 0], [set b : R | 0 < b]).
  - split.
    + exists 0%R; split; first exact: num_real.
      by move=> x /RltP.
    + exists 0%R; split; first exact: num_real.
      by move=> x /RltP.
  - move=> [a b] [/= Ha Hb]; simpl; lra.
Qed.

(* The hypothesis ex_RInt_gen gaussian_kernel ... becomes
   whole_line_integrable gaussian_kernel (header, item 1). *)
Lemma gaussian_has_integral_constant c :
  whole_line_integrable gaussian_kernel ->
  gaussian_has_integral (fun _ => c) (c * gaussian_mass).
Proof.
  move=> Hk; rewrite /gaussian_has_integral /whole_line_has_integral.
  split.
  - exact: (fubini_integrable_scale setT _ c measurableT Hk).
  - by rewrite /gaussian_mass (fubini_integral_scale_l _ c Hk).
Qed.

Lemma gaussian_integral_constant c :
  whole_line_integrable gaussian_kernel ->
  gaussian_integral (fun _ => c) = c * gaussian_mass.
Proof.
  intro Hk; apply gaussian_integral_unique; apply gaussian_has_integral_constant.
  exact Hk.
Qed.

Lemma gaussian_expectation_constant c :
  whole_line_integrable gaussian_kernel ->
  gaussian_mass <> 0 -> gaussian_expectation (fun _ => c) = c.
Proof.
  intros Hk Hm; unfold gaussian_expectation; rewrite (gaussian_integral_constant c Hk).
  field; exact Hm.
Qed.

Lemma gaussian_density_positive_given_mass x :
  0 < gaussian_mass -> 0 < gaussian_density x.
Proof.
  intro Hm; unfold gaussian_density; apply Rdiv_lt_0_compat; [apply exp_pos|exact Hm].
Qed.

(* The conclusion is_RInt_gen gaussian_density ... 1 becomes
   whole_line_has_integral gaussian_density 1 (header, items 1 and 2). *)
Lemma gaussian_density_normalized :
  whole_line_integrable gaussian_kernel ->
  gaussian_mass <> 0 ->
  whole_line_has_integral gaussian_density 1.
Proof.
  move=> Hk Hm.
  have E : gaussian_density = (fun x => / gaussian_mass * gaussian_kernel x).
  { apply/funext => x; unfold gaussian_density, Rdiv; ring. }
  rewrite /whole_line_has_integral E.
  split.
  - exact: (fubini_integrable_scale setT _ (/ gaussian_mass) measurableT Hk).
  - rewrite (fubini_integral_scale_l _ (/ gaussian_mass) Hk).
    change (/ gaussian_mass * gaussian_mass = 1); field; exact Hm.
Qed.

Lemma gaussian_has_integral_uniform_bound f l B :
  whole_line_integrable gaussian_kernel ->
  (forall x, Rabs (f x) <= B) -> gaussian_has_integral f l ->
  Rabs l <= B * gaussian_mass.
Proof.
  move=> Hk Hf [Hi Hl].
  rewrite -Hl /gaussian_mass.
  apply: (fubini_Rintegral_bound setT _ gaussian_kernel B measurableT Hi Hk).
  move=> x _.
  have Hk0 : gaussian_kernel x >= 0 by left; apply exp_pos.
  rewrite Rabs_mult (Rabs_right _ Hk0).
  apply Rmult_le_compat_r; [left; apply exp_pos|apply Hf].
Qed.

Theorem gaussian_density_positive x : 0 < gaussian_density x.
Proof. apply gaussian_density_positive_given_mass, gaussian_mass_positive. Qed.

Theorem gaussian_density_mass_one :
  whole_line_has_integral gaussian_density 1.
Proof.
  apply gaussian_density_normalized; [exact gaussian_kernel_integrable|].
  pose proof gaussian_mass_positive; lra.
Qed.

Theorem gaussian_expectation_of_constant c : gaussian_expectation (fun _ => c) = c.
Proof.
  apply gaussian_expectation_constant; [exact gaussian_kernel_integrable|].
  pose proof gaussian_mass_positive; lra.
Qed.

Theorem gaussian_expectation_uniform_bound f B :
  gaussian_integral_exists f -> (forall x, Rabs (f x) <= B) ->
  Rabs (gaussian_expectation f) <= B.
Proof.
  intros Hf HB.
  pose proof (gaussian_has_integral_uniform_bound f (gaussian_integral f) B
    gaussian_kernel_integrable HB (gaussian_integral_correct f Hf)) as HI.
  pose proof gaussian_mass_positive as HM.
  unfold gaussian_expectation, Rdiv.
  have HM0 : gaussian_mass >= 0 by lra.
  rewrite Rabs_mult Rabs_inv (Rabs_right _ HM0).
  apply (Rmult_le_reg_r gaussian_mass); [exact HM|].
  replace (Rabs (gaussian_integral f) * / gaussian_mass * gaussian_mass)
    with (Rabs (gaussian_integral f)) by (field; lra).
  exact HI.
Qed.

Lemma gaussian_integral_exists_scale f c :
  gaussian_integral_exists f -> gaussian_integral_exists (fun x => c * f x).
Proof.
  move=> Hf.
  exact: (proj1 (gaussian_has_integral_scale f _ c (gaussian_integral_correct f Hf))).
Qed.

Lemma gaussian_integral_exists_add f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_integral_exists (fun x => f x + g x).
Proof.
  move=> Hf Hg.
  exact: (proj1 (gaussian_has_integral_add f g _ _
    (gaussian_integral_correct f Hf) (gaussian_integral_correct g Hg))).
Qed.

Lemma gaussian_integral_exists_sub f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  gaussian_integral_exists (fun x => f x - g x).
Proof.
  move=> Hf Hg.
  exact: (proj1 (gaussian_has_integral_sub f g _ _
    (gaussian_integral_correct f Hf) (gaussian_integral_correct g Hg))).
Qed.

Lemma gaussian_has_integral_nonnegative f l :
  (forall x, 0 <= f x) -> gaussian_has_integral f l -> 0 <= l.
Proof.
  move=> Hf [_ Hl].
  rewrite -Hl /whole_line_integral.
  apply/RleP; apply: Rintegral_ge0 => x _.
  apply/RleP; apply Rmult_le_pos; [apply Hf|left; apply exp_pos].
Qed.

Theorem gaussian_expectation_nonnegative f :
  gaussian_integral_exists f -> (forall x, 0 <= f x) ->
  0 <= gaussian_expectation f.
Proof.
  intros Hf Hpos; unfold gaussian_expectation.
  apply Rdiv_le_0_compat.
  - exact (gaussian_has_integral_nonnegative f (gaussian_integral f)
      Hpos (gaussian_integral_correct f Hf)).
  - exact gaussian_mass_positive.
Qed.

Theorem gaussian_expectation_monotone f g :
  gaussian_integral_exists f -> gaussian_integral_exists g ->
  (forall x, f x <= g x) -> gaussian_expectation f <= gaussian_expectation g.
Proof.
  intros Hf Hg Hfg.
  assert (H : 0 <= gaussian_expectation (fun x => g x - f x)).
  { apply gaussian_expectation_nonnegative.
    - apply gaussian_integral_exists_sub; assumption.
    - intro x; specialize (Hfg x); lra. }
  rewrite (gaussian_expectation_sub g f Hg Hf) in H; lra.
Qed.

Theorem gaussian_expectation_absolute_bound f :
  gaussian_integral_exists f -> gaussian_absolutely_integrable f ->
  Rabs (gaussian_expectation f) <= gaussian_expectation (fun x => Rabs (f x)).
Proof.
  intros Hf Habs.
  have H := fubini_Rintegral_abs_le setT (fun x => f x * gaussian_kernel x)
    measurableT Hf.
  have E : (fun y => Rabs (f y * gaussian_kernel y)) =
      (fun y => Rabs (f y) * gaussian_kernel y).
  { apply/funext => y.
    have Hk0 : gaussian_kernel y >= 0 by left; apply exp_pos.
    by rewrite Rabs_mult (Rabs_right _ Hk0). }
  rewrite E in H.
  change (Rabs (gaussian_integral f) <= gaussian_integral (fun x => Rabs (f x))) in H.
  pose proof gaussian_mass_positive as HM.
  unfold gaussian_expectation, Rdiv.
  have HM0 : gaussian_mass >= 0 by lra.
  rewrite Rabs_mult Rabs_inv (Rabs_right _ HM0).
  apply Rmult_le_compat_r; [left; apply Rinv_0_lt_compat; exact HM|exact H].
Qed.

(* New lemmas for the importers (header, last paragraph). *)

Lemma gaussian_has_integral_exists f l :
  gaussian_has_integral f l -> gaussian_integral_exists f.
Proof. by move=> [Hi _]. Qed.

Lemma gaussian_integral_exists_iff f :
  gaussian_integral_exists f <-> exists l, gaussian_has_integral f l.
Proof.
  split.
  - move=> Hf; exists (gaussian_integral f); exact: gaussian_integral_correct.
  - move=> [l Hl]; exact: (gaussian_has_integral_exists f l Hl).
Qed.

Lemma gaussian_integral_exists_constant c :
  gaussian_integral_exists (fun _ => c).
Proof.
  exact: (gaussian_has_integral_exists _ _
    (gaussian_has_integral_constant c gaussian_kernel_integrable)).
Qed.

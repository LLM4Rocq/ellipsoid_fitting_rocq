(* Measurability of the coordinate polynomials of a sample, for the
   measurability conjuncts of paper_main_results. Internal proof module of
   the MathComp-Analysis port, written on 30 September 2026 by a Claude Code
   session (Fable 5.1); it edits no definition of the challenge. Nothing here
   is reviewed or accepted.

   The sample type paper_main_sample n d carries the product sigma-algebra
   generated by the coordinates tnth. A coordinate List.nth k (tval x) 0 is
   tnth x k for k < n * d and the constant 0 otherwise, so it is a measurable
   function; sums and products of measurable real functions are measurable
   (measurable_sum, measurable_funM, measurable_funD, measurable_cst of
   MathComp-Analysis); and the sets {x | f x < g x}, {x | f x <= g x},
   {x | f x = g x} for measurable f, g are preimages of an open or closed
   subset of R under the measurable function g - f. The quadratic forms of
   the glossary at a fixed matrix, the fit residuals at a fixed matrix, and
   the entries of the balanced combination at fixed weights are such
   polynomials. *)

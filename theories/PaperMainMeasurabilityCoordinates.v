(* List.nth against MathComp's nth. *)
Lemma pm_List_nth_nth (s : seq R) (k : nat) : List.nth k s 0 = nth 0 s k.
Proof. by elim: s k => [|a s IH] [|k] //=. Qed.

(* The k-th coordinate of a sample. *)
Definition pm_coord (k : nat) (x : T) : RT := List.nth k (tval x) 0.

Lemma pm_coord_measurable k : measurable_fun [set: T] (pm_coord k).
Proof.
have [kn|kn] := ltnP k (n * d)%nat.
- have -> : pm_coord k = (fun x : T => tnth x (Ordinal kn)).
    by apply/funext => x; rewrite /pm_coord pm_List_nth_nth (tnth_nth 0).
  exact: measurable_tnth.
- have -> : pm_coord k = (fun _ : T => (0 : RT)).
    apply/funext => x; rewrite /pm_coord pm_List_nth_nth nth_default//.
    by rewrite size_tuple.
  exact: measurable_cst.
Qed.

(* Entries of the points. *)
Lemma pm_point_entry_measurable (i : nat) (a : 'I_d) :
  measurable_fun [set: T] (fun x : T => (paper_main_point x i a 0 : RT)).
Proof.
have -> : (fun x : T => (paper_main_point x i a 0 : RT)) = pm_coord (i * d + a)%nat.
  by apply/funext => x; rewrite /paper_main_point mxE.
exact: pm_coord_measurable.
Qed.

Lemma pm_measurable_ordsum {m : nat} (h : 'I_m -> T -> R) :
  (forall i, measurable_fun [set: T] (fun x => (h i x : RT))) ->
  measurable_fun [set: T] (fun x => (\sum_(i < m) h i x : RT)).
Proof. by move=> mh; exact: measurable_sum. Qed.

Lemma pm_measurable_mul (f g : T -> R) :
  measurable_fun [set: T] (fun x => (f x : RT)) ->
  measurable_fun [set: T] (fun x => (g x : RT)) ->
  measurable_fun [set: T] (fun x => (f x * g x : RT)).
Proof. by move=> mf mg; exact: measurable_funM. Qed.

Lemma pm_measurable_sub (f g : T -> R) :
  measurable_fun [set: T] (fun x => (f x : RT)) ->
  measurable_fun [set: T] (fun x => (g x : RT)) ->
  measurable_fun [set: T] (fun x => (f x - g x : RT)).
Proof. by move=> mf mg; exact: measurable_funB. Qed.

Lemma pm_measurable_cst (c : R) : measurable_fun [set: T] (fun _ : T => (c : RT)).
Proof. exact: measurable_cst. Qed.

Lemma pm_measurable_scale (c : R) (f : T -> R) :
  measurable_fun [set: T] (fun x => (f x : RT)) ->
  measurable_fun [set: T] (fun x => (c * f x : RT)).
Proof. by move=> mf; apply: pm_measurable_mul => //; exact: pm_measurable_cst. Qed.

(* The sets defined by a comparison of two measurable functions. *)
Lemma pm_measurable_lt (f g : T -> R) :
  measurable_fun [set: T] (fun x => (f x : RT)) ->
  measurable_fun [set: T] (fun x => (g x : RT)) ->
  measurable [set x : T | f x < g x].
Proof.
move=> mf mg.
have mgf := measurable_funB mg mf.
have moA : measurable [set t : RT | 0 < t] by apply: open_measurable; exact: (@open_gt R 0).
have := mgf measurableT _ moA.
rewrite setTI => H.
rewrite (_ : [set x : T | f x < g x] = (fun x => (g x - f x : RT)) @^-1` [set t : RT | 0 < t])//.
by apply/seteqP; split=> x /=; rewrite subr_gt0.
Qed.

Lemma pm_measurable_le (f g : T -> R) :
  measurable_fun [set: T] (fun x => (f x : RT)) ->
  measurable_fun [set: T] (fun x => (g x : RT)) ->
  measurable [set x : T | f x <= g x].
Proof.
move=> mf mg.
have mgf := measurable_funB mg mf.
have moA : measurable [set t : RT | 0 <= t] by apply: closed_measurable; exact: (@closed_ge R 0).
have := mgf measurableT _ moA.
rewrite setTI => H.
rewrite (_ : [set x : T | f x <= g x] = (fun x => (g x - f x : RT)) @^-1` [set t : RT | 0 <= t])//.
by apply/seteqP; split=> x /=; rewrite subr_ge0.
Qed.

(* The quadratic form of the glossary at a fixed matrix, along a point. *)
Lemma pm_quadratic_form_measurable (S : 'M[R]_d) (i : nat) :
  measurable_fun [set: T]
    (fun x : T => (paper_main_quadratic_form S (paper_main_point x i) : RT)).
Proof.
rewrite /paper_main_quadratic_form.
refine (pm_measurable_ordsum (fun a x => \sum_(b < d)
  paper_main_point x i a 0 * S a b * paper_main_point x i b 0) _) => a.
refine (pm_measurable_ordsum (fun b x =>
  paper_main_point x i a 0 * S a b * paper_main_point x i b 0) _) => b.
refine (pm_measurable_mul (fun x => paper_main_point x i a 0 * S a b)
  (fun x => paper_main_point x i b 0) _ (pm_point_entry_measurable i b)).
refine (pm_measurable_mul (fun x => paper_main_point x i a 0) (fun _ => S a b)
  (pm_point_entry_measurable i a) _).
exact: pm_measurable_cst.
Qed.

(* The fit residual at a fixed matrix: sum over the points of the squared
   defect of the equation x_i^T S x_i = d. *)
Definition pm_fit_residual (S : 'M[R]_d) (x : T) : R :=
  \sum_(i < n) (paper_main_quadratic_form S (paper_main_point x i) - d%:R) ^+ 2.

Lemma pm_fit_residual_measurable (S : 'M[R]_d) :
  measurable_fun [set: T] (fun x => (pm_fit_residual S x : RT)).
Proof.
rewrite /pm_fit_residual.
refine (pm_measurable_ordsum (fun (i : 'I_n) x =>
  (paper_main_quadratic_form S (paper_main_point x i) - d%:R) ^+ 2) _) => i.
have h : measurable_fun [set: T]
    (fun x => (paper_main_quadratic_form S (paper_main_point x i) - d%:R : RT)).
  exact: (pm_measurable_sub (fun x => paper_main_quadratic_form S (paper_main_point x i))
    (fun _ => d%:R) (pm_quadratic_form_measurable S i) (pm_measurable_cst _)).
rewrite (_ : (fun x => _) = (fun x : T => ((paper_main_quadratic_form S (paper_main_point x i) - d%:R) *
  (paper_main_quadratic_form S (paper_main_point x i) - d%:R) : RT))).
  by apply/funext => x; rewrite expr2.
exact (pm_measurable_mul (fun x => paper_main_quadratic_form S (paper_main_point x i) - d%:R)
  (fun x => paper_main_quadratic_form S (paper_main_point x i) - d%:R) h h).
Qed.

(* Entries of the balanced combination sum_i y_i x_i x_i^T at fixed weights,
   and its quadratic form along a fixed vector. *)
Definition pm_balanced_matrix (y : 'I_n -> R) (x : T) : 'M[R]_d :=
  \sum_(i < n) y i *: (paper_main_point x i *m (paper_main_point x i)^T).

Lemma pm_balanced_matrix_entry (y : 'I_n -> R) (x : T) (a b : 'I_d) :
  pm_balanced_matrix y x a b = \sum_(i < n) y i * (paper_main_point x i a 0 * paper_main_point x i b 0).
Proof.
rewrite /pm_balanced_matrix summxE; apply: eq_bigr => i _.
by rewrite !mxE big_ord1 !mxE.
Qed.

Lemma pm_balanced_entry_measurable (y : 'I_n -> R) (a b : 'I_d) :
  measurable_fun [set: T] (fun x : T => (pm_balanced_matrix y x a b : RT)).
Proof.
rewrite (_ : (fun x => _) = (fun x : T => (\sum_(i < n) y i *
    (paper_main_point x i a 0 * paper_main_point x i b 0) : RT))).
  by apply/funext => x; rewrite pm_balanced_matrix_entry.
refine (pm_measurable_ordsum (fun (i : 'I_n) x =>
  y i * (paper_main_point x i a 0 * paper_main_point x i b 0)) _) => i.
refine (pm_measurable_scale (y i) (fun x => paper_main_point x i a 0 * paper_main_point x i b 0) _).
exact: (pm_measurable_mul (fun x => paper_main_point x i a 0) (fun x => paper_main_point x i b 0)
  (pm_point_entry_measurable i a) (pm_point_entry_measurable i b)).
Qed.

Lemma pm_balanced_quadratic_form_measurable (y : 'I_n -> R) (v : 'cV[R]_d) :
  measurable_fun [set: T]
    (fun x : T => (paper_main_quadratic_form (pm_balanced_matrix y x) v : RT)).
Proof.
rewrite /paper_main_quadratic_form.
refine (pm_measurable_ordsum (fun a x => \sum_(b < d)
  v a 0 * pm_balanced_matrix y x a b * v b 0) _) => a.
refine (pm_measurable_ordsum (fun b x => v a 0 * pm_balanced_matrix y x a b * v b 0) _) => b.
refine (pm_measurable_mul (fun x => v a 0 * pm_balanced_matrix y x a b) (fun _ => v b 0)
  _ (pm_measurable_cst _)).
exact: (pm_measurable_mul (fun _ => v a 0) (fun x => pm_balanced_matrix y x a b)
  (pm_measurable_cst _) (pm_balanced_entry_measurable y a b)).
Qed.

